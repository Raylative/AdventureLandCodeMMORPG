const pixelSize = 12;


async function drawText(text) {
    let convertedText = text.toUpperCase();
    let offsetY = -100
    let originX = character.x
    let originY = character.y + offsetY
    let glyph = FONT[" "];
    let colOffset = -((text.length*(glyph[0].length+1))/2);
    
    for(let letter of convertedText){
         glyph = FONT[letter];

        for (let row in glyph) {
            for (let col in glyph[row]) {
                if (glyph[row][col] === 1) {
                    let EggInventoryIndex = locate_item("whiteegg")
                    if (EggInventoryIndex===-1){return;}
                    let xCordinateEgg =originX+Number(col)*pixelSize+Number(colOffset)*pixelSize;
                    let yCordinateEgg =originY+Number(row)*pixelSize;
                    await throw_item(EggInventoryIndex,xCordinateEgg ,yCordinateEgg );
                }
            }
        }
        colOffset += glyph.length+1;
    }
}


